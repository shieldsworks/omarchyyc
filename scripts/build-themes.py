"""Generate website tokens from the checked-in Omarchy palette snapshot."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = json.loads((ROOT / 'themes/palettes.json').read_text())
PALETTES = DATA['palettes']
LABELS = {'rose-pine': 'Rosé Pine', 'tokyo-night': 'Tokyo Night'}


def luminance(color):
    rgb = [int(color[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    return sum(c * w for c, w in zip(
        [v / 12.92 if v <= 0.04045 else ((v + 0.055) / 1.055) ** 2.4 for v in rgb],
        [0.2126, 0.7152, 0.0722]))


def contrast(a, b):
    light, dark = sorted([luminance(a), luminance(b)], reverse=True)
    return (light + 0.05) / (dark + 0.05)


def tokens(palette):
    backgrounds = [palette[k] for k in ('background', 'dark_background', 'lighter_background')]
    colors = [v for v in palette.values() if v.startswith('#') and len(v) == 7]

    def readable(preferred, minimum=4.5):
        for color in [palette[k] for k in preferred] + colors:
            if all(contrast(color, bg) >= minimum for bg in backgrounds):
                return color
        raise ValueError('No readable palette color')

    text = readable(['foreground', 'bright_foreground'])
    secondary = readable(['light_foreground', 'foreground'])
    accent = readable(['accent', 'cyan', 'blue', 'green', 'magenta'])
    ink = max(colors, key=lambda c: contrast(c, accent))
    assert contrast(ink, accent) >= 4.5
    return {
        'bg': palette['background'], 'bg-deep': palette['dark_background'],
        'surface': palette['background'], 'surface-2': palette['lighter_background'],
        'border-subtle': palette['muted'], 'border-strong': readable(['muted'], 3),
        'text': text, 'text-secondary': secondary, 'text-muted': secondary,
        'brand': accent, 'brand-hover': accent, 'brand-soft': palette['lighter_background'],
        'brand-foam': text, 'brand-ink': ink,
    }


def rule(selector, palette):
    declarations = {'color-scheme': palette['mode']}
    declarations.update({'--' + k: v for k, v in tokens(palette).items()})
    return selector + ' {\n' + ''.join(f'  {k}: {v};\n' for k, v in declarations.items()) + '}\n'


css = '/* Generated by scripts/build-themes.py from themes/palettes.json. */\n'
css += '@media (prefers-color-scheme: light) {\n' + rule(':root:not([data-theme])', PALETTES['catppuccin-latte']) + '}\n'
for name, palette in PALETTES.items():
    css += rule(f':root[data-theme="{name}"]', palette)
(ROOT / 'css/themes.css').write_text(css)

options = '<option value="auto">Auto</option>\n'
options += '\n'.join(f'<option value="{name}">{LABELS.get(name, name.replace("-", " ").title())}</option>' for name in PALETTES)
control = '      <label class="theme-picker" hidden>Theme\n        <select id="theme-select">\n' + options + '\n        </select>\n      </label>\n'
head = '''  <script>
    try {
      const theme = localStorage.getItem('oyc-theme');
      if (THEMES.includes(theme)) document.documentElement.dataset.theme = theme;
    } catch (_) {}
  </script>
  <link rel="stylesheet" href="/css/themes.css">
  <script src="/js/theme.js" defer></script>
'''.replace('THEMES', json.dumps(list(PALETTES), separators=(',', ':')))
for path in ROOT.glob('*.html'):
    html = path.read_text()
    if '<!-- theme-head -->' in html:
        start, rest = html.split('  <!-- theme-head -->\n', 1)
        _, end = rest.split('  <!-- /theme-head -->\n', 1)
        html = start + end
    html = html.replace('  <link rel="stylesheet" href="/css/styles.css">', '  <link rel="stylesheet" href="/css/styles.css">\n  <!-- theme-head -->\n' + head + '  <!-- /theme-head -->')
    if '<!-- theme-control -->' in html:
        start, rest = html.split('      <!-- theme-control -->\n', 1)
        _, end = rest.split('      <!-- /theme-control -->\n', 1)
        html = start + end
    html = html.replace('      </nav>\n', '      </nav>\n      <!-- theme-control -->\n' + control + '      <!-- /theme-control -->\n')
    path.write_text(html)
print(f'Generated {len(PALETTES)} themes across {len(list(ROOT.glob("*.html")))} pages.')
